import assert from "node:assert/strict";
import { mkdir, rm } from "node:fs/promises";
import { join, resolve } from "node:path";
import test from "node:test";
import { createPithWebServer } from "../src/shells/web/server.ts";
import { linkedEpub } from "./wave12-epub-fixture.ts";
import { testSandbox } from "./sandbox.ts";

test("Web mounts the shared workbench and connects reading and interline", { timeout: 60000, skip: !process.env.PITH_PLAYWRIGHT_MODULE || !process.env.PITH_CHROME_PATH }, async () => {
  const { chromium } = await import(process.env.PITH_PLAYWRIGHT_MODULE!);
  const dir = await testSandbox("task23-shared-");
  await mkdir(join(dir, "workspace"));
  const server = await createPithWebServer({ workspaceDir: join(dir, "workspace"), guideProvider: { run: async (_input, options) => { options.onStep({ kind: "reply", markdown: "受控向导回复" }, 0); return { status: "completed" }; } }, interlineTranslator: async input => new Map(input.segments.map(segment => [segment.locator, "测试译文"])) });
  const address = server.address(); assert.ok(address && typeof address !== "string");
  const base = `http://127.0.0.1:${address.port}`;
  const post = async (path: string, body: unknown) => { const response = await fetch(base + path, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) }); if (!response.ok) throw new Error(await response.text()); return response.json(); };
  const browser = await chromium.launchPersistentContext(join(dir, "profile"), { executablePath: process.env.PITH_CHROME_PATH, headless: true, viewport: { width: 1400, height: 900 }, args: ["--use-fake-device-for-media-stream", "--use-fake-ui-for-media-stream"] });
  try {
    const topic = await post("/api/topics", { title: "共享工作台" });
    await post("/api/materials", { topicId: topic.id, title: "book", kind: "book", files: [{ name: "book.epub", data: Buffer.from(linkedEpub()).toString("base64") }] });
    await post(`/api/topics/${topic.id}/toolkits`, { toolkits: ["interline"] });
    const page = await browser.newPage(); page.setDefaultTimeout(5000); const errors: string[] = []; let sends = 0;
    page.on("pageerror", (error: Error) => errors.push(error.message));
    page.on("request", (request: { method(): string; url(): string }) => { if (request.method() === "POST" && request.url().endsWith("/api/chat")) sends++; });
    await browser.grantPermissions(["microphone"], { origin: base });
    await page.addInitScript(() => {
      const state: { streams: MediaStream[] } = { streams: [] };
      (window as unknown as { syntheticVoice: typeof state }).syntheticVoice = state;
      navigator.mediaDevices.getUserMedia = async () => { const context = new AudioContext(); const source = context.createOscillator(); const destination = context.createMediaStreamDestination(); source.connect(destination); source.start(); await context.resume(); state.streams.push(destination.stream); return destination.stream; };
    });
    await page.route("**/api/agents?force=true", (route: { fulfill(options: object): Promise<void> }) => route.fulfill({ json: [] }));
    await page.route("**/api/speech/transcribe", (route: { request(): { postDataJSON(): { audio: string; mimeType: string } }; fulfill(options: object): Promise<void> }) => { const body = route.request().postDataJSON(); assert.equal(body.mimeType, "audio/webm"); assert.ok(Buffer.from(body.audio, "base64").length > 0); return route.fulfill({ json: { text: "受控转写" } }); });
    await page.goto(base);
    assert.equal(await page.locator(".pith-home h1").textContent(), "课题看板");
    await page.locator(`[data-topic="${topic.id}"]`).first().click();
    await page.locator(".pith-view .pith-article .pith-epub-chapter").first().waitFor();
    await page.locator(".pith-view #open-toolkit").click();
    await page.locator('[data-toolkit-choose="interline"]').click();
    await page.locator('.pith-toolkit-panel [data-interline-mode="bilingual"]').click();
    await page.locator(".pith-article .pith-interline-subtitle").first().waitFor();
    await page.locator('[data-command="typography"]').click(); await page.locator('[data-mode="double"]').click();
    assert.equal(await page.locator('[data-mode="double"]').getAttribute("aria-pressed"), "true");
    await page.locator(".pith-guide-toggle").click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('[data-command="settings"]').click();
    await page.locator("#close-drawer").click();
    await page.locator(".pith-guide-toggle").click();
    await page.locator(".pith-guide-toggle").click();
    const mobileBounds = await page.evaluate(() => ({ left: document.querySelector(".pith-view")!.getBoundingClientRect().left, width: document.documentElement.scrollWidth, viewport: window.innerWidth }));
    assert.equal(mobileBounds.left, 0);
    assert.equal(mobileBounds.width, mobileBounds.viewport);
    await page.setViewportSize({ width: 1400, height: 900 });
    assert.equal(await page.locator('.pith-guide [data-voice]').count(), 0);
    await page.locator('#open-toolkit').click(); await page.locator('[data-toolkit-choose="shadowing"]').click();
    await page.locator('[data-voice="toolkit"]').click();
    await page.waitForFunction(() => document.querySelector('[data-voice="toolkit"]')?.getAttribute("aria-pressed") === "true");
    await page.waitForTimeout(300);
    await page.locator('[data-voice="toolkit"]').click();
    await page.waitForFunction(() => document.querySelector('.pith-shadowing-feedback')?.textContent?.includes('受控转写'));
    assert.equal(await page.evaluate(() => { const streams = (window as unknown as { syntheticVoice: { streams: MediaStream[] } }).syntheticVoice.streams; return streams.length === 1 && streams[0]!.getTracks().every(track => track.readyState === "ended"); }), true);
    const evidence = resolve('.tmp/evidence/task-37'); await mkdir(evidence, { recursive: true }); await page.screenshot({ path: join(evidence, 'web-shadowing-light.png') });
    await page.locator('.pith-guide-toggle').click(); await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ colorScheme: 'dark' }); await page.screenshot({ path: join(evidence, 'web-shadowing-dark-narrow.png') }); await page.emulateMedia({ colorScheme: 'light' }); await page.setViewportSize({ width: 1400, height: 900 }); await page.locator('.pith-guide-toggle').click();
    await page.locator(".pith-guide textarea").fill("受控问题");
    await page.locator("[data-guide-send]").click();
    await page.getByText("受控向导回复").last().waitFor();
    assert.equal(sends, 1);
    await page.route("**/api/chat", (route: { fulfill(options: object): Promise<void> }) => route.fulfill({ status: 503, json: { error: "受控向导故障" } }));
    await page.locator(".pith-guide textarea").fill("待重试问题"); await page.locator("[data-guide-send]").click();
    await page.locator("[data-guide-error]").getByText("受控向导故障").waitFor();
    assert.equal(await page.locator(".pith-guide textarea").inputValue(), "待重试问题");
    await page.route("**/api/speech/synthesize", (route: { fulfill(options: object): Promise<void> }) => route.fulfill({ status: 503, contentType: "application/json", body: '{"error":"受控语音故障"}' }));
    await page.locator('[data-command="read"]').click();
    await page.getByText(/受控语音故障/).waitFor();
    await page.locator('[data-command="home"]').click();
    await page.locator("[data-home-settings]").click();
    await page.locator("#simple-mode").waitFor();
    await page.locator("#close-drawer").click();
    await page.locator('.pith-intake-box input[name="title"]').fill("新课题");
    await page.locator("[data-intake-open]").click();
    await page.getByText("这个课题还没有关联材料。").waitFor();
    await page.locator("#material-files").setInputFiles({ name: "material.md", mimeType: "text/markdown", buffer: Buffer.from("# Imported\n\nA real imported paragraph.") });
    await page.getByText("A real imported paragraph.").waitFor();
    assert.deepEqual(errors, []);
  } finally { await browser.close(); await new Promise<void>((resolve, reject) => server.close(error => error ? reject(error) : resolve())); await rm(dir, { recursive: true, force: true }); }
});
